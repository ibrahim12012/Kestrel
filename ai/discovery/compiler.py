"""
ai/discovery/compiler.py
==========================
Atomic Macro Compilation Pipeline - spec section 4.

Not used by the app any more. A mapping run used to compile and register
one AI tool per control, which made the AI's tool list hundreds long
and gave it functions that clicked where a control had been when the
map was made. ai/actions.py's tool_use_mapped_control presses a mapped
control by name instead, looked up in the window as it is now. This
stays for anyone who wants the generated module itself.

Rather than one monolithic macro per multi-step task, every distinct
action discovered by the mapper (ai/discovery/mapper.py) becomes its
own independent, parameterized Python function - "Atomic Function
Isolation". A multi-step task is then just several of these called in
sequence by whatever's planning the task (the AI's normal tool-calling
loop, or a hand-written script), not something baked into one macro.

Two things happen at compile time, both driven off the SAME tree the
mapper already built:

  1. A standalone module is written to disk - spec section 5's "Atomic
     Action Repository (ai/NameApp_actions.py)" artifact - readable,
     diffable, and importable on its own.
  2. The identical source is also exec'd directly into ai.actions's live
     namespace (register_compiled_actions), the same technique
     ai/macro_store.py already uses for learned macros - so the actions
     are immediately callable by Gemini's automatic function calling
     with zero extra registration step, without ai/actions.py itself
     ever being rewritten.

Naming: the spec's own example names functions like
`click_search_bar()` - bare, no prefix. This app's tool-discovery
mechanism (ai.actions.get_all_tools) only picks up functions starting
with "tool_", so generated functions here are named
`tool_<node_id>_<action_slug>` instead: unique by construction (node ids
are unique), and immediately usable as real Gemini tools once merged
into ai.actions, which is what actually makes them useful to "any
non-visual LLM" as the spec's section 5 intends.

Safety Interception Hooks (spec section 4): every DiscoveredAction the
mapper flagged as destructive (ai.safety.is_destructive_label - see
ai/discovery/mapper.py) compiles with an extra `confirmed: bool = False`
parameter and refuses to run unless it's explicitly True, mirroring the
confirm-before-destructive-actions pattern ai/instructions.txt already
teaches the model for tool_run_command et al.

Every piece of AI/UI-authored text (element names, app names, paths) is
inserted via repr(), never string-formatted directly into source - same
discipline as ai/macro_generalizer.py's render_function - and the whole
module is ast.parse()-validated before it's written or exec'd.
"""

from __future__ import annotations

import ast
import os

import ai.safety as safety
from ai.discovery.tree import ActionTree
from ai.log import log as print
from paths import USER_DATA_PATH

# Under USER_DATA_PATH, alongside the trees these are compiled from (see
# ai/discovery/tree.py's TREES_DIR), not next to the executable. Same
# three reasons instructions.txt moved (ai/main.py's INSTRUCTIONS_PATH):
# Program Files is not writable by a standard user, an upgrade would wipe
# the directory, and an app that writes .py files into its own install
# folder and then executes them is describing a dropper to any antivirus
# engine watching. The exec below is unchanged and still only ever runs
# source rendered from a validated tree, but where that source lands on
# disk is free to be somewhere less alarming. See docs/ANTIVIRUS.md.
GENERATED_DIR = os.path.join(USER_DATA_PATH, "ai", "generated")

_HEADER_TEMPLATE = '''"""
{filename}
{underline}
AUTO-GENERATED by ai/discovery/compiler.py from a mapping run of {app_name!r}.
Do not hand-edit - re-run discovery to regenerate. See
ai/discovery/tree.py for the source State Graph Matrix this was compiled
from (ai/discovery/trees/{tree_slug}_tree.json).

Every function here resolves its target live via the accessibility path
recorded at mapping time, falling back to a bounding-box click if the UI
has changed since then - see ai/discovery/runtime.py.
"""

from ai.discovery.runtime import resolve_and_activate, resolve_and_input

APP_NAME = {app_name!r}
'''


def _atomic_function_source(app_name: str, node_id: str, action) -> "tuple[str, str]":
    """Returns (function_name, source_text) for one DiscoveredAction."""
    from ai.actions import _sanitize_macro_name

    base = _sanitize_macro_name(f"{node_id}_{action.action_id}")
    kind = "input" if action.requires_input else "click"
    fn_name = f"tool_{kind}_{base}"

    doc = (
        f"Compiled atomic action from node {node_id} of the {app_name} action tree. "
        f"Element type: {action.element_type}. "
        f"{'Types the given text into this field.' if action.requires_input else 'Clicks/activates this element.'}"
    )
    if action.is_destructive:
        doc += " DESTRUCTIVE - requires confirmed=True."

    lines = []
    if action.requires_input:
        params = "text_value: str" + (", confirmed: bool = False" if action.is_destructive else "")
        lines.append(f"def {fn_name}({params}) -> str:")
    else:
        params = "confirmed: bool = False" if action.is_destructive else ""
        lines.append(f"def {fn_name}({params}) -> str:")
    lines.append(f"    {doc!r}")

    if action.is_destructive:
        lines.append("    if not confirmed:")
        lines.append(f"        return {'Refused: ' + action.action_id + ' is destructive - call again with confirmed=True after the user confirms.'!r}")

    if action.requires_input:
        lines.append(f"    return resolve_and_input({app_name!r}, {action.accessibility_path!r}, text_value, {action.bounding_box!r})")
    else:
        lines.append(f"    return resolve_and_activate({app_name!r}, {action.accessibility_path!r}, {action.bounding_box!r})")

    return fn_name, "\n".join(lines) + "\n"


def render_module(tree: ActionTree) -> str:
    """
    Pure codegen, no I/O - one atomic function per discovered action
    across every node in `tree`, deduplicated by function name (the same
    UI element reachable via two different navigation paths compiles to
    one function, not two identical copies).
    """
    from ai.actions import _sanitize_macro_name

    tree_slug = _sanitize_macro_name(tree.app_name)
    filename = f"{tree.app_name}_actions.py"
    header = _HEADER_TEMPLATE.format(
        filename=filename,
        underline="=" * len(filename),
        app_name=tree.app_name,
        tree_slug=tree_slug,
    )

    seen_names = set()
    blocks = []
    for node_id, node in sorted(tree.nodes.items()):
        for action in node.discovered_actions:
            fn_name, source = _atomic_function_source(tree.app_name, node_id, action)
            if fn_name in seen_names:
                continue
            seen_names.add(fn_name)
            blocks.append(source)

    return header + "\n\n" + "\n\n".join(blocks) + "\n"


def compile_action_tree(tree: ActionTree, out_dir: "str | None" = None) -> str:
    """
    Writes the Atomic Action Repository to disk (spec section 5) and
    validates it's syntactically sound before doing so. Returns the path
    written. Does NOT register the functions as live Gemini tools - call
    register_compiled_actions() separately for that (kept apart so
    "write the artifact" and "make it live in this running process" can
    be tested/reasoned about independently).
    """
    source = render_module(tree)
    try:
        ast.parse(source)
    except SyntaxError as e:
        raise ValueError(f"Compiled action module for {tree.app_name!r} is not valid Python: {e}") from e

    out_dir = out_dir or GENERATED_DIR
    os.makedirs(out_dir, exist_ok=True)
    path = compiled_path(tree.app_name, out_dir)
    with open(path, "w", encoding="utf-8") as f:
        f.write(source)

    print(f"[discovery.compiler] Compiled {len(tree.nodes)} node(s) / {tree.action_count()} action(s) -> {path}")
    return path


def compiled_path(app_name: str, out_dir: "str | None" = None) -> str:
    """Where the code compiled from an app's map is written: named like
    its map (ai/discovery/tree.py's file_stem)."""
    from ai.discovery.tree import file_stem
    return os.path.join(out_dir or GENERATED_DIR, f"{file_stem(app_name)}_actions.py")


def register_compiled_actions(actions_module, tree: ActionTree) -> int:
    """
    Exec's the same generated source directly into actions_module's
    namespace (ai.actions.__dict__), the same technique
    ai.macro_store.register_macro already uses for learned macros - so
    the compiled tool_click_*/tool_input_* functions are immediately
    picked up by get_all_tools() with no separate registration step.
    Returns how many functions were registered. Never raises; a bad
    render is logged and skipped, same contract as macro_store.
    """
    source = render_module(tree)
    try:
        ast.parse(source)
        exec(compile(source, f"<discovery:{tree.app_name}>", "exec"), actions_module.__dict__)
    except Exception as e:
        print(f"[discovery.compiler] Failed to register compiled actions for {tree.app_name!r}: {e}")
        return 0

    count = sum(
        1 for name in actions_module.__dict__
        if name.startswith("tool_click_") or name.startswith("tool_input_")
    )
    print(f"[discovery.compiler] Registered compiled actions for {tree.app_name!r} into ai.actions.")
    return count
