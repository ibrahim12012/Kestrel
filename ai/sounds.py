"""
ai/sounds.py
==============
Sound effects: playing them, and not playing them twice.

The sounds themselves are assets/sounds/<kind>.wav, generated by
tools/make_sounds.py. A WAV dropped in with the same name replaces one.

Played through the Windows waveOut API, on a background thread, instead
of the winsound module the app used before:

  - winsound.Beep is the PC-speaker beep, and it blocks the calling
    thread for as long as it sounds. Several callers were the GUI
    thread, so the window froze for every beep.
  - winsound.PlaySound has one channel per process, and Read aloud
    plays speech through it (ai.main._play_pcm). A sound effect on that
    channel cut Kestrel off mid-sentence.

waveOut streams are mixed by Windows like any other audio, so an effect
plays over speech instead of replacing it, and play() returns at once.

The same sound asked for twice within REPEAT_WINDOW seconds plays once:
one event reported by two code paths is still one event. That, plus the
explicit rules in ai.main and ai.actions (a stopped run does not also
announce that it finished), is what stops sounds doubling up.

Outside Windows, and when sound is turned off in Settings, play() does
nothing.
"""

from __future__ import annotations

import os
import queue
import sys
import threading
import time
import wave

from paths import BASE_PATH
from ai.log import log_debug

SOUND_DIR = os.path.join(BASE_PATH, "assets", "sounds")

KINDS = (
    "screenshot",
    "listen_start",
    "listen_end",
    "wake_word",
    "confirm_accept",
    "confirm_refuse",
    "macro_finished",
    "automation_finished",
    "automation_stopped",
    "human_handoff",
)

# The same sound again inside this window is the same event reported
# twice (a held hotkey auto-repeating, two code paths both announcing
# one outcome), not a second event.
REPEAT_WINDOW = 0.8

_lock = threading.Lock()
_last_played: dict = {}
_cache: dict = {}
_queue: "queue.Queue[tuple]" = queue.Queue()
_worker: "threading.Thread | None" = None
_device_failed = False


def is_available() -> bool:
    return sys.platform == "win32"


def play(kind: str, wait: bool = False) -> bool:
    """
    Queue `kind` to play. Returns at once unless `wait`, in which case it
    returns when the sound has finished (used before opening the
    microphone, so the mic doesn't hear the "listening" sound itself).

    False when it was skipped: an unknown kind, a repeat inside
    REPEAT_WINDOW, or no audio on this platform.
    """
    if kind not in KINDS or not is_available():
        return False
    now = time.monotonic()
    with _lock:
        last = _last_played.get(kind)
        if last is not None and now - last < REPEAT_WINDOW:
            return False
        _last_played[kind] = now
        _ensure_worker()
    done = threading.Event() if wait else None
    _queue.put((kind, done))
    if done is not None:
        done.wait(3.0)
    return True


def played_since(kind: str, since: float) -> bool:
    """Whether `kind` was played at or after `since` (time.monotonic())."""
    with _lock:
        last = _last_played.get(kind)
    return last is not None and last >= since


def _ensure_worker() -> None:
    global _worker
    if _worker is None or not _worker.is_alive():
        _worker = threading.Thread(target=_run, name="sound-effects", daemon=True)
        _worker.start()


def _run() -> None:
    while True:
        kind, done = _queue.get()
        try:
            clip = _load(kind)
            if clip is not None:
                _play_clip(*clip)
        except Exception as e:  # noqa: BLE001 - a sound must never take anything down
            log_debug(f"[sounds] couldn't play {kind!r}: {e}")
        finally:
            if done is not None:
                done.set()


def _load(kind: str):
    """(pcm, rate, channels, sample_width) for a kind, read once."""
    if kind in _cache:
        return _cache[kind]
    path = os.path.join(SOUND_DIR, f"{kind}.wav")
    clip = None
    try:
        with wave.open(path, "rb") as w:
            clip = (w.readframes(w.getnframes()), w.getframerate(), w.getnchannels(), w.getsampwidth())
    except (OSError, wave.Error) as e:
        log_debug(f"[sounds] {path} unreadable: {e}")
    _cache[kind] = clip
    return clip


def _play_clip(pcm: bytes, rate: int, channels: int, sample_width: int) -> None:
    """Play one buffer through waveOut and wait for it to finish (on this
    worker thread, never the caller's)."""
    global _device_failed
    import ctypes
    from ctypes import wintypes

    class WAVEFORMATEX(ctypes.Structure):
        _fields_ = [
            ("wFormatTag", wintypes.WORD),
            ("nChannels", wintypes.WORD),
            ("nSamplesPerSec", wintypes.DWORD),
            ("nAvgBytesPerSec", wintypes.DWORD),
            ("nBlockAlign", wintypes.WORD),
            ("wBitsPerSample", wintypes.WORD),
            ("cbSize", wintypes.WORD),
        ]

    class WAVEHDR(ctypes.Structure):
        pass

    WAVEHDR._fields_ = [
        ("lpData", ctypes.c_void_p),
        ("dwBufferLength", wintypes.DWORD),
        ("dwBytesRecorded", wintypes.DWORD),
        ("dwUser", ctypes.c_size_t),
        ("dwFlags", wintypes.DWORD),
        ("dwLoops", wintypes.DWORD),
        ("lpNext", ctypes.POINTER(WAVEHDR)),
        ("reserved", ctypes.c_size_t),
    ]

    WAVE_MAPPER = 0xFFFFFFFF
    WAVE_FORMAT_PCM = 1
    WHDR_DONE = 0x1

    winmm = ctypes.WinDLL("winmm")
    winmm.waveOutOpen.argtypes = [ctypes.POINTER(ctypes.c_void_p), wintypes.UINT, ctypes.POINTER(WAVEFORMATEX),
                                  ctypes.c_size_t, ctypes.c_size_t, wintypes.DWORD]
    winmm.waveOutPrepareHeader.argtypes = [ctypes.c_void_p, ctypes.POINTER(WAVEHDR), wintypes.UINT]
    winmm.waveOutWrite.argtypes = [ctypes.c_void_p, ctypes.POINTER(WAVEHDR), wintypes.UINT]
    winmm.waveOutUnprepareHeader.argtypes = [ctypes.c_void_p, ctypes.POINTER(WAVEHDR), wintypes.UINT]
    winmm.waveOutReset.argtypes = [ctypes.c_void_p]
    winmm.waveOutClose.argtypes = [ctypes.c_void_p]

    fmt = WAVEFORMATEX()
    fmt.wFormatTag = WAVE_FORMAT_PCM
    fmt.nChannels = channels
    fmt.nSamplesPerSec = rate
    fmt.wBitsPerSample = sample_width * 8
    fmt.nBlockAlign = channels * sample_width
    fmt.nAvgBytesPerSec = rate * fmt.nBlockAlign
    fmt.cbSize = 0

    device = ctypes.c_void_p()
    result = winmm.waveOutOpen(ctypes.byref(device), WAVE_MAPPER, ctypes.byref(fmt), 0, 0, 0)
    if result != 0:
        if not _device_failed:
            _device_failed = True
            log_debug(f"[sounds] no audio output available (waveOutOpen error {result})")
        return
    _device_failed = False

    buffer = ctypes.create_string_buffer(pcm, len(pcm))
    header = WAVEHDR()
    header.lpData = ctypes.cast(buffer, ctypes.c_void_p)
    header.dwBufferLength = len(pcm)
    size = ctypes.sizeof(WAVEHDR)
    try:
        if winmm.waveOutPrepareHeader(device, ctypes.byref(header), size) != 0:
            return
        try:
            if winmm.waveOutWrite(device, ctypes.byref(header), size) != 0:
                return
            duration = len(pcm) / float(fmt.nAvgBytesPerSec or 1)
            deadline = time.monotonic() + duration + 1.0
            while not (header.dwFlags & WHDR_DONE) and time.monotonic() < deadline:
                time.sleep(0.01)
        finally:
            winmm.waveOutReset(device)
            winmm.waveOutUnprepareHeader(device, ctypes.byref(header), size)
    finally:
        winmm.waveOutClose(device)
